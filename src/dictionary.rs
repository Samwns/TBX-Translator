static DICT_MAP: OnceLock<HashMap<String, &'static StandardTerm>> = OnceLock::new();

fn get_dict_map() -> &'static HashMap<String, &'static StandardTerm> {
    DICT_MAP.get_or_init(|| {
        let mut map = HashMap::with_capacity(STANDARD_TERMS.len() * 2);
        for term in STANDARD_TERMS {
            map.insert(term.key.to_lowercase(), term);
        }
        map
    })
}

/// Normalizes a query string by removing surrounding quotes and trimming.
fn normalize_query(text: &str) -> String {
    let mut s = text.trim();
    if (s.starts_with('"') && s.ends_with('"')) || (s.starts_with('\'') && s.ends_with('\'')) {
        if s.len() >= 2 {
            s = &s[1..s.len() - 1];
        }
    }
    s.trim().to_lowercase()
}

/// Looks up a standard visual novel/game engine interface term and returns
/// the official pre-translated term for the target language code.
pub fn lookup(text: &str, target_lang_code: &str) -> Option<&'static str> {
    let query = normalize_query(text);
    if query.is_empty() {
        return None;
    }

    let map = get_dict_map();
    let term = map.get(&query)?;

    let trans = match target_lang_code {
        "pt" | "pt-BR" | "pt-PT" => term.pt,
        "es" => term.es,
        "en" => term.en,
        "fr" => term.fr,
        "de" => term.de,
        "it" => term.it,
        "ru" => term.ru,
        "uk" => term.uk,
        "ja" => term.ja,
        "zh-CN" | "zh" => term.zh_cn,
        "ko" => term.ko,
        _ => return None,
    };

    Some(trans)
}

